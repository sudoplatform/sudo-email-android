package com.sudoplatform.sudoemail.types.inputs

import com.sudoplatform.sudoemail.SudoEmailClient
import com.sudoplatform.sudoemail.types.EmailAliasRealAddressType
import com.sudoplatform.sudoemail.types.EmailAliasStatus

sealed interface EmailAliasStatusFilterInput

/**
 * @property equal [EmailAliasStatus] Return only results that match the given state.
 */
data class EqualStatusFilter(
    val equal: EmailAliasStatus,
) : EmailAliasStatusFilterInput

/**
 * @property oneOf [List<EmailAliasStatus>] Return only results that match one of the given states.
 */
data class OneOfStatusFilter(
    val oneOf: List<EmailAliasStatus>,
) : EmailAliasStatusFilterInput

/**
 * @property notEqual [EmailAliasStatus] Return only results that do not match the given state.
 */
data class NotEqualStatusFilter(
    val notEqual: EmailAliasStatus,
) : EmailAliasStatusFilterInput

/**
 * @property notOneOf [List<EmailAliasStatus>] Return only results that do not match any of the given states.
 */
data class NotOneOfStatusFilter(
    val notOneOf: List<EmailAliasStatus>,
) : EmailAliasStatusFilterInput

sealed interface EmailAliasRealAddressTypeFilterInput

data class EqualRealAddressTypeFilter(
    val equal: EmailAliasRealAddressType,
) : EmailAliasRealAddressTypeFilterInput

data class OneOfRealAddressTypeFilter(
    val oneOf: List<EmailAliasRealAddressType>,
) : EmailAliasRealAddressTypeFilterInput

data class NotEqualRealAddressTypeFilter(
    val notEqual: EmailAliasRealAddressType,
) : EmailAliasRealAddressTypeFilterInput

data class NotOneOfRealAddressTypeFilter(
    val notOneOf: List<EmailAliasRealAddressType>,
) : EmailAliasRealAddressTypeFilterInput

/**
 * @property status [EmailAliasStatusFilterInput] Used to filter results based on `status` property
 */
data class EmailAliasFilterInput(
    val status: EmailAliasStatusFilterInput? = null,
    val realAddressType: EmailAliasRealAddressTypeFilterInput? = null,
)

/**
 * Input object containing email address id and other parameters used to list email aliases for
 * an owner.
 *
 * @property limit [Int] Number of records to return. If omitted, the limit defaults to 10.
 * @property nextToken [String] A token generated by a previous call to [SudoEmailClient.listEmailAliasesForOwner].
 * This is to allow for pagination. This value should be generated from a previous
 * pagination call, otherwise it will throw an exception. The same arguments should be
 * supplied to this method if using a previously generated [nextToken].
 * @property filter [EmailAliasFilterInput] Properties used to filter the results.
 */
data class ListEmailAliasesForOwnerInput(
    val limit: Int? = null,
    val nextToken: String? = null,
    val filter: EmailAliasFilterInput? = null,
)
